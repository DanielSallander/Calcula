fn src_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR")).join("src")
}

fn rust_files(dir: &Path, out: &mut Vec<PathBuf>) {
    let mut entries: Vec<_> = std::fs::read_dir(dir).expect("read src dir").flatten().collect();
    entries.sort_by_key(|e| e.path());
    for e in entries {
        let p = e.path();
        if p.is_dir() {
            rust_files(&p, out);
        } else if p.extension().is_some_and(|x| x == "rs") {
            out.push(p);
        }
    }
}

fn rel(path: &Path) -> String {
    path.strip_prefix(src_dir())
        .unwrap()
        .components()
        .map(|c| c.as_os_str().to_string_lossy().into_owned())
        .collect::<Vec<_>>()
        .join("/")
}

/// Blank comments and the CONTENTS of string, raw-string and char literals
/// (quotes kept, newlines kept, every other byte a space), so the scan sees
/// code only. Lifetimes (`'a`) are left alone.
fn mask(src: &str) -> String {
    let b: Vec<char> = src.chars().collect();
    let mut out: Vec<char> = Vec::with_capacity(b.len());
    let blank = |c: char| if c == '\n' { '\n' } else { ' ' };
    let mut i = 0;
    while i < b.len() {
        let c = b[i];
        // Line comment.
        if c == '/' && b.get(i + 1) == Some(&'/') {
            while i < b.len() && b[i] != '\n' {
                out.push(' ');
                i += 1;
            }
            continue;
        }
        // Block comment (nesting, as Rust allows).
        if c == '/' && b.get(i + 1) == Some(&'*') {
            let mut depth = 0;
            while i < b.len() {
                if b[i] == '/' && b.get(i + 1) == Some(&'*') {
                    depth += 1;
                    out.push(' ');
                    out.push(' ');
                    i += 2;
                } else if b[i] == '*' && b.get(i + 1) == Some(&'/') {
                    depth -= 1;
                    out.push(' ');
                    out.push(' ');
                    i += 2;
                    if depth == 0 {
                        break;
                    }
                } else {
                    out.push(blank(b[i]));
                    i += 1;
                }
            }
            continue;
        }
        // Raw string r"..." / r#"..."# (also br"...").
        if c == 'r' && (b.get(i + 1) == Some(&'"') || b.get(i + 1) == Some(&'#')) {
            let prev_ident = i > 0 && (b[i - 1].is_alphanumeric() || b[i - 1] == '_') && b[i - 1] != 'b';
            if !prev_ident {
                let mut j = i + 1;
                let mut hashes = 0;
                while b.get(j) == Some(&'#') {
                    hashes += 1;
                    j += 1;
                }
                if b.get(j) == Some(&'"') {
                    for _ in i..=j {
                        out.push(' ');
                    }
                    out.pop();
                    out.push('"');
                    j += 1;
                    loop {
                        if j >= b.len() {
                            break;
                        }
                        if b[j] == '"' && (0..hashes).all(|h| b.get(j + 1 + h) == Some(&'#')) {
                            out.push('"');
                            for _ in 0..hashes {
                                out.push(' ');
                            }
                            j += 1 + hashes;
                            break;
                        }
                        out.push(blank(b[j]));
                        j += 1;
                    }
                    i = j;
                    continue;
                }
            }
        }
        // Ordinary string.
        if c == '"' {
            out.push('"');
            i += 1;
            while i < b.len() && b[i] != '"' {
                if b[i] == '\\' && i + 1 < b.len() {
                    out.push(' ');
                    out.push(blank(b[i + 1]));
                    i += 2;
                    continue;
                }
                out.push(blank(b[i]));
                i += 1;
            }
            out.push('"');
            i += 1;
            continue;
        }
        // Char literal: 'x' or '\n' / '\'' / '\u{..}'. A lifetime is not one.
        if c == '\'' {
            if b.get(i + 1) == Some(&'\\') {
                let mut j = i + 2;
                while j < b.len() && b[j] != '\'' {
                    j += 1;
                }
                for _ in i..=j.min(b.len() - 1) {
                    out.push(' ');
                }
                i = j + 1;
                continue;
            }
            if b.get(i + 2) == Some(&'\'') {
                out.push(' ');
                out.push(' ');
                out.push(' ');
                i += 3;
                continue;
            }
        }
        out.push(c);
        i += 1;
    }
    out.into_iter().collect()
}

/// Remove every `#[cfg(test)]` item from MASKED source (see the module doc).
fn strip_cfg_test(masked: &str) -> String {
    const ATTR: &str = "#[cfg(test)]";
    let mut out = String::with_capacity(masked.len());
    let mut i = 0;
    while let Some(off) = masked[i..].find(ATTR) {
        let j = i + off;
        out.push_str(&masked[i..j]);
        let k = j + ATTR.len();
        let rest = &masked[k..];
        let semi = rest.find(';');
        let brace = rest.find('{');
        match (semi, brace) {
            (Some(s), Some(b)) if s < b => {
                i = k + s + 1;
            }
            (Some(s), None) => {
                i = k + s + 1;
            }
            (_, Some(b)) => {
                let mut depth = 0i64;
                let mut end = masked.len();
                for (n, ch) in masked[k + b..].char_indices() {
                    match ch {
                        '{' => depth += 1,
                        '}' => {
                            depth -= 1;
                            if depth == 0 {
                                end = k + b + n + 1;
                                break;
                            }
                        }
                        _ => {}
                    }
                }
                i = end;
            }
            (None, None) => {
                i = masked.len();
            }
        }
    }
    out.push_str(&masked[i.min(masked.len())..]);
    out
}

/// The production text the census scans for one file.
fn scanned(path: &Path) -> String {
    let src = std::fs::read_to_string(path).unwrap_or_else(|e| panic!("read {}: {e}", path.display()));
    strip_cfg_test(&mask(&src))
}

fn scanned_rel(relative: &str) -> String {
    scanned(&src_dir().join(relative))
}

fn is_skipped_file(path: &Path) -> bool {
    let name = path.file_name().unwrap().to_string_lossy();
    name.ends_with("_tests.rs") || name == "tests.rs"
}

/// Name of the `fn` whose header most recently precedes each line.
fn fn_name_in(line: &str) -> Option<String> {
    let mut search = line;
    while let Some(pos) = search.find("fn ") {
        let before_ok = pos == 0 || !search[..pos].chars().last().is_some_and(|c| c.is_alphanumeric() || c == '_');
        let after = &search[pos + 3..];
        let name: String = after.trim_start().chars().take_while(|c| c.is_alphanumeric() || *c == '_').collect();
        if before_ok && !name.is_empty() {
            return Some(name);
        }
        search = &search[pos + 3..];
    }
    None
}

fn is_locale_write(line: &str) -> bool {
    let reads_locale = line.contains("locale.lock()") || line.contains("locale.write()");
    if !reads_locale {
        return false;
    }
    let trimmed = line.trim_start();
    let let_mut = trimmed.starts_with("let mut ") && line.contains(".locale.");
    let deref_assign = trimmed.starts_with('*') && {
        let after = &line[line.find("locale.").unwrap()..];
        after.contains(") =") || after.contains(")=") || after.contains("() =")
    };
    let_mut || deref_assign
}

/// Every hit in production code: (file, fn, pattern) -> count.
fn census() -> BTreeMap<(String, String, String), usize> {
    let mut files = Vec::new();
    rust_files(&src_dir(), &mut files);
    let mut hits = BTreeMap::new();
    for path in files.iter().filter(|p| !is_skipped_file(p)) {
        let text = scanned(path);
        let file = rel(path);
        let mut current_fn = String::new();
        for line in text.lines() {
            if let Some(name) = fn_name_in(line) {
                current_fn = name;
            }
            for pattern in [INVARIANT, SIMPLE_VALUE, SIMPLE_NUMBER] {
                let count = line.matches(pattern).count();
                if count > 0 {
                    *hits.entry((file.clone(), current_fn.clone(), pattern.to_string())).or_insert(0) += count;
                }
            }
            if is_locale_write(line) {
                *hits.entry((file.clone(), current_fn.clone(), WRITE.to_string())).or_insert(0) += 1;
            }
        }
    }
    hits
}

/// The body of `fn name` in a scanned (masked, stripped) text.
fn fn_body<'a>(text: &'a str, name: &str) -> Option<&'a str> {
    let mut from = 0;
    while let Some(off) = text[from..].find(&format!("fn {name}")) {
        let start = from + off;
        let after = &text[start + 3 + name.len()..];
        let boundary_ok = after.chars().next().is_some_and(|c| c == '(' || c == '<' || c.is_whitespace());
        if boundary_ok {
            let open = start + text[start..].find('{')?;
            let mut depth = 0i64;
            for (n, ch) in text[open..].char_indices() {
                match ch {
                    '{' => depth += 1,
                    '}' => {
                        depth -= 1;
                        if depth == 0 {
                            return Some(&text[start..open + n + 1]);
                        }
                    }
                    _ => {}
                }
            }
            return None;
        }
        from = start + 3;
    }
    None
}

