//! FILENAME: app/src-tauri/src/display_locale_census_tests.rs
//! PURPOSE: P2 S5 -- the Rust DISPLAY-LOCALE census. The owner rule is "app
//!          locale everywhere": every display string the backend writes uses
//!          the APP locale (`state.locale`, or the `app_locale` mirror for
//!          code with no `AppState`). This census makes a regression a test
//!          failure with the file named, instead of a German user reading
//!          "1,234.50" somewhere nobody looked.
//!
//! WHAT IT SCANS. Every `app/src-tauri/src/**/*.rs` file, PRODUCTION code
//! only:
//! - files named `*_tests.rs` and `tests.rs` are skipped whole;
//! - every `#[cfg(test)]` ITEM is removed by brace matching (the attribute,
//!   the item header, through its matching `}`; a `#[cfg(test)] mod name;`
//!   declaration is removed through its `;`). The scan NEVER truncates a file
//!   at its first `#[cfg(test)]`: `lib.rs` declares test modules near its top,
//!   and stopping there would hide `create_app_state` and
//!   `format_cell_value_simple` -- the hazard `profile_dir.rs` documents.
//! - comments and string/char literal CONTENTS are blanked first, so a
//!   comment that mentions `#[cfg(test)]` or `invariant()` neither strips
//!   code nor counts as a hit, and a `{` inside a string never unbalances
//!   the brace matching.
//!
//! WHAT IT LOOKS FOR. `LocaleSettings::invariant()`,
//! `format_cell_value_simple(`, `format_number_simple(`, and WRITES to the
//! app locale (`let mut .. = ..locale.lock()` / `*..locale.lock().. =`).
//! Every hit must be on [`ALLOWLIST`] as (file, enclosing fn, pattern), each
//! with its reason. The allowlist was generated by running this census once
//! on the swept tree (2026-10-17) and classifying EVERY hit; a new hit fails
//! with the file and function named.
//!
//! POSITIVE CHECKS. The display sites P2 moved (and P3's styled cell read,
//! `cell_target::get_cell_target_cells_inner`, critic C6) must still READ
//! `state.locale` -- a function that silently stopped reading it would pass
//! the ban list while showing the engine default.

