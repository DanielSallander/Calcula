#[test]
fn the_stripper_and_masker_on_a_synthetic_file() {
    let src = r##"
fn keep_one() { let a = LocaleSettings::invariant(); }
// a comment: #[cfg(test)] fn not_an_item() {
#[cfg(test)]
mod declared;
#[cfg(test)]
mod inline {
    fn hidden() { let s = "}{"; let c = '{'; let r = r#"{"#; LocaleSettings::invariant(); }
}
/* block #[cfg(test)] { */
fn keep_two<'a>(x: &'a str) -> &'a str { let t = "LocaleSettings::invariant()"; x }
"##;
    let out = strip_cfg_test(&mask(src));
    assert!(out.contains("fn keep_one"));
    assert!(out.contains("fn keep_two"), "a brace in a comment or literal unbalanced the match:\n{out}");
    assert!(!out.contains("hidden"));
    assert!(!out.contains("declared"));
    assert_eq!(out.matches(INVARIANT).count(), 1, "only the production call counts, never a string:\n{out}");
    assert_eq!(fn_name_in("    pub(crate) fn foo_bar<T>(x: T) {"), Some("foo_bar".to_string()));
    assert!(is_locale_write("        *state.locale.lock().unwrap() = x;"));
    assert!(is_locale_write("    let mut slot = state.locale.lock().unwrap();"));
    assert!(!is_locale_write("    let locale = state.locale.lock().unwrap().clone();"));
}

#[test]
fn the_census_scans_files_and_finds_the_known_writer() {
    let hits = census();
    assert!(
        hits.contains_key(&("app_locale.rs".to_string(), "install".to_string(), WRITE.to_string())),
        "the census no longer sees app_locale::install writing state.locale -- the WRITE rule is blind"
    );
    let mut files = Vec::new();
    rust_files(&src_dir(), &mut files);
    assert!(files.len() > 100, "the census walked only {} files", files.len());
}
