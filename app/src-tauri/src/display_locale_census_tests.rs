#[test]
fn every_invariant_display_hit_in_production_is_allowlisted() {
    let hits = census();
    let unexpected: Vec<String> = hits
        .keys()
        .filter(|(file, func, pattern)| {
            !ALLOWLIST
                .iter()
                .any(|(f, n, p, _)| f == file && n == func && p == pattern)
        })
        .map(|(file, func, pattern)| format!("  {file} :: fn {func} :: {pattern}"))
        .collect();
    assert!(
        unexpected.is_empty(),
        "display text outside the app locale (P2 S5 census). Each hit below either uses the app \
         locale (state.locale, or format_cell_value_display / value_to_display_localized) or, if it \
         is truly a comparison, key or machine text, goes on ALLOWLIST with its reason:\n{}",
        unexpected.join("\n")
    );
}

#[test]
fn no_allowlist_entry_is_stale() {
    let hits = census();
    let stale: Vec<String> = ALLOWLIST
        .iter()
        .filter(|(f, n, p, _)| !hits.contains_key(&(f.to_string(), n.to_string(), p.to_string())))
        .map(|(f, n, p, why)| format!("  {f} :: fn {n} :: {p} ({why})"))
        .collect();
    assert!(
        stale.is_empty(),
        "allowlist entries that no longer match a hit -- remove them so the list cannot quietly \
         grant a future regression:\n{}",
        stale.join("\n")
    );
}

#[test]
fn the_display_sites_read_the_app_locale_from_state() {
    for (file, func) in MUST_READ_STATE_LOCALE {
        let text = scanned_rel(file);
        let body = fn_body(&text, func).unwrap_or_else(|| panic!("{file}: fn {func} not found"));
        assert!(
            body.contains("state.locale.lock()"),
            "{file}: fn {func} no longer reads state.locale (the app locale)"
        );
        assert!(!body.contains(INVARIANT), "{file}: fn {func} uses the invariant locale");
    }
}

