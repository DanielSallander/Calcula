/// `NAME(A1,A1,..)` with `count` arguments.
fn call(name: &str, count: usize) -> String {
    format!("{}({})", name, vec!["A1"; count].join(","))
}

/// Every count Excel typed is written, with Excel's prefix; every count it
/// refused is a formula Excel cannot hold. Each call is stored under the
/// name it was typed with: until lane legacystats (2026-11-05) Calcula's
/// parser stored the compatibility functions under the modern name
/// (`NORMSDIST(z)` as `NORM.S.DIST(z)`, which the export then had to write
/// value-only) and some modern ones under the compatibility name (`STDEV.P`
/// as `STDEVP`), and this test skipped or re-routed those calls; now a
/// renamed call is itself a failure.
/// SABOTAGE (legacystats-name): NORMSDIST stored as NORM.S.DIST again -- fails
/// with `NORMSDIST(A1) is stored as NORM.S.DIST(A1)`; (legacystats-arity): an
/// optional second NORMSDIST argument -- `NORMSDIST(A1,A1)` written though
/// Excel refuses it.
#[test]
fn every_call_excel_types_is_written_and_every_call_it_refuses_is_not() {
    let mut wrong = Vec::new();
    let mut checked = 0usize;
    for &(name, prefix, typed, refused) in EXCEL_TYPED {
        for (&count, excel_types) in typed.iter().map(|c| (c, true)).chain(refused.iter().map(|c| (c, false))) {
            let input = call(name, count);
            let Some(stored) = crate::SavedCell::from_cell(&engine::Cell::new_formula(format!("={}", input))).formula else { continue };
            let stored = stored.trim_start_matches('=').to_string();
            let stored_name = stored.split('(').next().unwrap_or_default().to_string();
            if !stored_name.eq_ignore_ascii_case(name) {
                wrong.push(format!("  {} is stored as {}: the call was renamed", input, stored));
                continue;
            }
            checked += 1;
            let reason = unwritable_reason(&stored, Some((1, 9)));
            if excel_types {
                let text = escape_future_functions(&excel_formula_text(&stored, Some((1, 9))));
                let expected = format!("{}{}", prefix, stored);
                if reason.is_some() || !text.eq_ignore_ascii_case(&expected) {
                    wrong.push(format!("  {} (stored {}): Excel types it as {}; Calcula: {:?} / {}", input, stored, expected, reason, text));
                }
            } else if reason != Some(Unwritable::BuiltinArity) {
                wrong.push(format!("  {} (stored {}): Excel REFUSES it; Calcula writes it ({:?})", input, stored, reason));
            }
        }
    }
    assert!(checked > 1500, "only {} calls checked", checked);
    assert!(wrong.is_empty(), "NOT AS EXCEL ({}):\n{}", wrong.len(), wrong.join("\n"));
}
