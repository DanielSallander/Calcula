#[test]
fn ceiling_and_floor_round_as_excel_does_for_every_sign_significance_and_mode() {
    let grid = Grid::new();
    let mut wrong = Vec::new();
    for (formula, excel) in EXCEL {
        let ast = parser::parse(formula).unwrap_or_else(|e| panic!("{formula} must parse: {e:?}"));
        let got = Evaluator::new(&grid).evaluate(&ast);
        let ok = match (excel, &got) {
            (N(want), EvalResult::Number(n)) => (n - want).abs() <= 1e-15 * want.abs().max(1.0),
            (E(want), EvalResult::Error(e)) => e == want,
            _ => false,
        };
        if !ok {
            let want = match excel { N(n) => format!("{n}"), E(e) => format!("{e:?}") };
            wrong.push(format!("{formula}: Calcula {got:?}, [LIVE] Excel {want}"));
        }
    }
    assert!(wrong.is_empty(), "{} of {} wrong:\n{}", wrong.len(), EXCEL.len(), wrong.join("\n"));
}
